#!/usr/bin/env bash
# Source of truth for add-guardrails: the ESLint ban set, its wiring, and the AGENTS.md section.
# Invoked by the add-guardrails skill.
set -euo pipefail

if [[ $# -ne 1 ]]; then
  echo "usage: init.sh <absolute-target-directory>" >&2
  exit 2
fi

TARGET="$1"

if [[ "$TARGET" != /* ]]; then
  echo "add-guardrails: target must be an absolute path (got: $TARGET)" >&2
  exit 2
fi

if [[ ! -d "$TARGET" ]]; then
  echo "add-guardrails: target directory does not exist: $TARGET" >&2
  exit 1
fi

cd "$TARGET"

# src/ projects keep everything under src/ (matches add-shadcn and add-env).
if [[ -d src/app ]]; then
  ROOT=src/
else
  ROOT=
fi
ENV_FILE="${ROOT}lib/env.ts"
RULES_FILE=eslint.guardrails.mjs
CONFIG_FILE=eslint.config.mjs
CONFIG_EXPORT='export default eslintConfig;'

if [[ ! -f "$CONFIG_FILE" ]]; then
  echo "add-guardrails: $CONFIG_FILE not found — only the create-next-app flat config is supported. Aborting." >&2
  exit 1
fi

if ! grep -qx "$CONFIG_EXPORT" "$CONFIG_FILE"; then
  echo "add-guardrails: $CONFIG_FILE has no '$CONFIG_EXPORT' line — refusing to edit a customized config. Aborting." >&2
  exit 1
fi

if [[ -e "$RULES_FILE" ]]; then
  echo "add-guardrails: $RULES_FILE already exists — guardrails appear initialized. Aborting." >&2
  exit 1
fi

if [[ ! -f "$ENV_FILE" ]]; then
  echo "add-guardrails: $ENV_FILE not found — the process.env ban needs the typed env module. Run add-env first. Aborting." >&2
  exit 1
fi

cat > "$RULES_FILE" <<EOF
// Generated by add-guardrails. Bans are errors with no inline escape.
const ROOT = "${ROOT}";
const EXT = "{js,jsx,mjs,cjs,ts,tsx,mts,cts}";

const EFFECT_MESSAGE =
  "Effects are banned. Derive values during render, handle events in handlers, reset state with a key, read external stores with useSyncExternalStore, fetch on the server. If none fit, stop and ask a human.";

const restrictedImports = (extraPatterns = []) => [
  "error",
  {
    patterns: [
      {
        regex: "(^|/)features/[^/]+/.",
        message: "Import a feature only through its public API: @/features/<name>.",
      },
      ...extraPatterns,
    ],
  },
];

// Relative imports inside features/<name>/ may not climb out of the feature.
const featureDepthBlocks = Array.from({ length: 8 }, (_, depth) => ({
  files: [\`\${ROOT}features/*/\${"*/".repeat(depth)}*.\${EXT}\`],
  rules: {
    "no-restricted-imports": restrictedImports([
      {
        regex: \`^(\\\\.\\\\./){\${depth + 1},}\`,
        message: "Relative imports may not leave the feature. Use @/features/<name> for other features, @/ for shared code.",
      },
    ]),
  },
}));

const guardrails = [
  {
    files: [\`**/*.\${EXT}\`],
    ignores: [\`\${ROOT}components/ui/**\`],
    linterOptions: { noInlineConfig: true },
    rules: {
      "no-restricted-imports": restrictedImports(),
      "no-restricted-syntax": [
        "error",
        {
          selector: "ImportDeclaration[source.value='react'] > ImportSpecifier[imported.name=/^use(Layout|Insertion)?Effect\$/]",
          message: EFFECT_MESSAGE,
        },
        {
          selector: "MemberExpression[property.name=/^use(Layout|Insertion)?Effect\$/]",
          message: EFFECT_MESSAGE,
        },
      ],
      "no-restricted-properties": [
        "error",
        { object: "process", property: "env", message: 'Read env through \`import { env } from "@/lib/env"\`.' },
      ],
    },
  },
  ...featureDepthBlocks,
  {
    files: [\`\${ROOT}lib/env.ts\`, \`*.config.\${EXT}\`],
    rules: { "no-restricted-properties": "off" },
  },
];

export default guardrails;
EOF

# Wire the rules in last so they apply on top of eslint-config-next.
node -e '
const fs = require("fs");
const [file, exp] = process.argv.slice(1);
const lines = fs.readFileSync(file, "utf8").split("\n");
let lastImport = -1;
lines.forEach((l, i) => { if (/^import\s/.test(l)) lastImport = i; });
lines.splice(lastImport + 1, 0, "import guardrails from \"./eslint.guardrails.mjs\";");
const at = lines.indexOf(exp);
lines.splice(at, 0, "eslintConfig.push(...guardrails);", "");
fs.writeFileSync(file, lines.join("\n"));
' "$CONFIG_FILE" "$CONFIG_EXPORT"

if [[ -f AGENTS.md ]] && ! grep -qx '## Guardrails' AGENTS.md; then
  if [[ -n "$(tail -c1 AGENTS.md)" ]]; then echo >> AGENTS.md; fi
  cat >> AGENTS.md <<EOF

## Guardrails

\`pnpm lint\` enforces the bans in \`eslint.guardrails.mjs\`: no effects, \`process.env\` only in \`${ENV_FILE}\`, features imported only through \`@/features/<name>\`. Inline \`eslint-disable\` comments have no effect. Never edit \`eslint.guardrails.mjs\` or ESLint ignores to get past a ban — change the code, or stop and ask.
EOF
fi

echo "add-guardrails: wrote $RULES_FILE, wired $CONFIG_FILE$( [[ -f AGENTS.md ]] && echo ', AGENTS.md section' )"
