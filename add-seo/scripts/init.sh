#!/usr/bin/env bash
# Source of truth for add-seo: NEXT_PUBLIC_SITE_URL in add-env's lib/env.ts, lib/site.ts, root metadata,
# sitemap, robots, and Open Graph image. Invoked by the add-seo skill. Next.js built-ins only; no packages.
set -euo pipefail

if [[ $# -ne 1 ]]; then
  echo "usage: init.sh <absolute-target-directory>" >&2
  exit 2
fi

TARGET="$1"

if [[ "$TARGET" != /* ]]; then
  echo "add-seo: target must be an absolute path (got: $TARGET)" >&2
  exit 2
fi

if [[ ! -d "$TARGET" ]]; then
  echo "add-seo: target directory does not exist: $TARGET" >&2
  exit 1
fi

if ! command -v node >/dev/null 2>&1; then
  echo "add-seo: node is required but was not found on PATH" >&2
  exit 1
fi

cd "$TARGET"

# src/ projects keep app/ and lib/ under src/ (matches add-shadcn and add-env).
if [[ -d src/app ]]; then
  APP_DIR=src/app
  LIB_DIR=src/lib
else
  APP_DIR=app
  LIB_DIR=lib
fi

# Rerun guard: lib/site.ts is the marker. Nothing is touched.
if [[ -e "$LIB_DIR/site.ts" ]]; then
  echo "add-seo: already initialized ($LIB_DIR/site.ts exists). Nothing changed." >&2
  exit 1
fi

if ! grep -q '"@t3-oss/env-nextjs"' package.json 2>/dev/null || [[ ! -f "$LIB_DIR/env.ts" ]]; then
  echo "add-seo: add-env has not run ($LIB_DIR/env.ts or @t3-oss/env-nextjs missing). Run add-env first. Aborting." >&2
  exit 1
fi

if ! grep -qF "import \"./$LIB_DIR/env\";" next.config.ts 2>/dev/null; then
  echo "add-seo: next.config.ts does not import ./$LIB_DIR/env — env validation is not wired. Aborting." >&2
  exit 1
fi

if [[ ! -f "$APP_DIR/layout.tsx" ]]; then
  echo "add-seo: $APP_DIR/layout.tsx not found. Aborting." >&2
  exit 1
fi

for f in "$APP_DIR"/sitemap.* "$APP_DIR"/robots.* "$APP_DIR"/opengraph-image.*; do
  if [[ -e "$f" ]]; then
    echo "add-seo: $f already exists — refusing to merge with existing SEO config. Aborting." >&2
    exit 1
  fi
done

# Validate env.ts and layout.tsx first, then write everything. Any failed check exits before the first write.
APP_DIR="$APP_DIR" LIB_DIR="$LIB_DIR" node -e '
const fs = require("fs");
const { APP_DIR, LIB_DIR } = process.env;
const fail = (msg) => { console.error("add-seo: " + msg + " Aborting."); process.exit(1); };
const count = (s, sub) => s.split(sub).length - 1;

// --- lib/env.ts: the two shapes add-env generates (one-line empty blocks, or multi-line blocks).
const envPath = `${LIB_DIR}/env.ts`;
let env = fs.readFileSync(envPath, "utf8");
const urlDeclared = env.includes("NEXT_PUBLIC_SITE_URL");
if (!urlDeclared) {
  const shapeOk =
    count(env, "import { createEnv } from \"@t3-oss/env-nextjs\";\n") === 1 &&
    count(env, "  client: {") === 1 &&
    count(env, "  runtimeEnv: {") === 1 &&
    /^  client: \{(\},|\n)/m.test(env) &&
    /^  runtimeEnv: \{(\},|\n)/m.test(env);
  if (!shapeOk) fail(`${envPath} does not match add-env output — add NEXT_PUBLIC_SITE_URL by hand.`);
  const insert = (src, key, line) =>
    src.includes(`  ${key}: {},`)
      ? src.replace(`  ${key}: {},`, `  ${key}: {\n    ${line}\n  },`)
      : src.replace(`  ${key}: {\n`, `  ${key}: {\n    ${line}\n`);
  env = insert(env, "client", "NEXT_PUBLIC_SITE_URL: z.url(),");
  env = insert(env, "runtimeEnv", "NEXT_PUBLIC_SITE_URL: process.env.NEXT_PUBLIC_SITE_URL,");
  if (!env.includes("import { z } from \"zod\";")) {
    env = env.replace(
      "import { createEnv } from \"@t3-oss/env-nextjs\";\n",
      "import { createEnv } from \"@t3-oss/env-nextjs\";\nimport { z } from \"zod\";\n",
    );
  }
}

// --- layout.tsx: replace the untouched create-next-app default, or add metadata when absent.
const layoutPath = `${APP_DIR}/layout.tsx`;
let layout = fs.readFileSync(layoutPath, "utf8");
const DEFAULT_META =
  "export const metadata: Metadata = {\n" +
  "  title: \"Create Next App\",\n" +
  "  description: \"Generated by create next app\",\n" +
  "};";
const SEO_META =
  "// No canonical or openGraph.url here: Next.js would inherit them on every page. Set them per page.\n" +
  "export const metadata: Metadata = {\n" +
  "  metadataBase: new URL(site.url),\n" +
  "  title: { default: site.name, template: `%s | ${site.name}` },\n" +
  "  description: site.description,\n" +
  "  openGraph: { siteName: site.name, type: \"website\" },\n" +
  "};";
if (layout.includes(DEFAULT_META)) {
  layout = layout.replace(DEFAULT_META, SEO_META);
} else if (/export\s+(const\s+metadata\b|(async\s+)?function\s+generateMetadata\b)/.test(layout)) {
  fail(`${layoutPath} has customized metadata — merge SEO settings by hand.`);
} else {
  const at = layout.indexOf("export default function");
  if (at === -1) fail(`${layoutPath} has no default export to place metadata above.`);
  layout = layout.slice(0, at) + SEO_META + "\n\n" + layout.slice(at);
}
if (!/import\s+(type\s+)?\{[^}]*\bMetadata\b[^}]*\}\s+from\s+"next";/.test(layout)) {
  layout = "import type { Metadata } from \"next\";\n" + layout;
}
const imports = [...layout.matchAll(/^import .*;$/gm)];
const last = imports[imports.length - 1];
const siteImport = "import { site } from \"@/lib/site\";";
const end = last.index + last[0].length;
layout = layout.slice(0, end) + "\n" + siteImport + layout.slice(end);

// --- package.json name (never asked).
const name = JSON.parse(fs.readFileSync("package.json", "utf8")).name;
if (!name) fail("package.json has no name.");

// --- All checks passed: write.
fs.writeFileSync(envPath, env);
fs.writeFileSync(layoutPath, layout);

if (!urlDeclared) {
  const appendLine = (file, line) => {
    const cur = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    if (/^\s*(export\s+)?NEXT_PUBLIC_SITE_URL\s*=/m.test(cur)) return;
    const sep = cur.length && !cur.endsWith("\n") ? "\n" : "";
    fs.writeFileSync(file, cur + sep + line + "\n");
  };
  appendLine(".env.example", "NEXT_PUBLIC_SITE_URL=");
  appendLine(".env.local", "NEXT_PUBLIC_SITE_URL=http://localhost:3000");
}

// Content is never invented: every value the developer must write is marked TODO(seo) (see AGENTS.md ## SEO).
fs.writeFileSync(`${LIB_DIR}/site.ts`, `import { env } from "@/lib/env";

// SEO source of truth. Search the project for TODO(seo) to find values still to write.
export const site = {
  name: ${JSON.stringify(name)},
  description: "TODO(seo): one sentence describing the site, used as the meta and Open Graph description.",
  // Fallback keeps SKIP_ENV_VALIDATION builds (CI without secrets) working; validation requires the real URL.
  url: env.NEXT_PUBLIC_SITE_URL ?? "http://localhost:3000",
  // Every public route, listed by hand. Dynamic routes (e.g. blog slugs) go in sitemap.ts.
  routes: ["/"],
} as const;
`);

fs.writeFileSync(`${APP_DIR}/sitemap.ts`, `import type { MetadataRoute } from "next";
import { site } from "@/lib/site";

export default function sitemap(): MetadataRoute.Sitemap {
  return site.routes.map((route) => ({ url: new URL(route, site.url).toString() }));
}
`);

fs.writeFileSync(`${APP_DIR}/robots.ts`, `import type { MetadataRoute } from "next";
import { site } from "@/lib/site";

export default function robots(): MetadataRoute.Robots {
  return {
    rules: { userAgent: "*", allow: "/" },
    sitemap: new URL("/sitemap.xml", site.url).toString(),
  };
}
`);

fs.writeFileSync(`${APP_DIR}/opengraph-image.tsx`, `import { ImageResponse } from "next/og";
import { site } from "@/lib/site";

export const alt = site.name;
export const size = { width: 1200, height: 630 };
export const contentType = "image/png";

export default function OpengraphImage() {
  return new ImageResponse(
    (
      <div
        style={{
          width: "100%",
          height: "100%",
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
          background: "#0a0a0a",
          color: "#fafafa",
          fontSize: 96,
        }}
      >
        {site.name}
      </div>
    ),
    size,
  );
}
`);

const SEO_SECTION = `
## SEO

- Site-wide SEO values live in \`${LIB_DIR}/site.ts\`: \`name\`, \`description\`, \`url\`, \`routes\`. Edit them there, not in \`${APP_DIR}/layout.tsx\`.
- Search for \`TODO(seo)\` to find values still to write. Replace the whole string; leave no marker behind.
- Add each new public route to \`site.routes\` so it appears in \`/sitemap.xml\`.
- Give each page its own canonical: \`export const metadata = { title: "…", alternates: { canonical: "/path" } }\`. The root layout sets none on purpose, because Next.js would inherit it on every page.
- \`NEXT_PUBLIC_SITE_URL\` must be the production URL in production. The build fails if it is missing or not a URL.
`;
const agentsUpdated = fs.existsSync("AGENTS.md") && !/^## SEO$/m.test(fs.readFileSync("AGENTS.md", "utf8"));
if (agentsUpdated) {
  const cur = fs.readFileSync("AGENTS.md", "utf8");
  fs.writeFileSync("AGENTS.md", cur + (cur.endsWith("\n") ? "" : "\n") + SEO_SECTION);
}

console.log(`add-seo: wrote ${LIB_DIR}/site.ts, ${APP_DIR}/sitemap.ts, ${APP_DIR}/robots.ts, ${APP_DIR}/opengraph-image.tsx; updated ${APP_DIR}/layout.tsx` +
  (urlDeclared ? " (NEXT_PUBLIC_SITE_URL already declared — env untouched)" : `, ${envPath}, .env.example, .env.local`) +
  (agentsUpdated ? ", AGENTS.md" : ""));
'
